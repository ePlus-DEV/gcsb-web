export function applyCompleteFacilitatorTranslations(catalogs) {
  for (const [locale, catalog] of Object.entries(catalogs)) {
    catalog.additional ??= {}
    const target = TRANSLATIONS[locale] ?? {}

    for (const [key, source] of Object.entries(SOURCES)) {
      if (locale !== "en" && !Object.hasOwn(target, key)) {
        throw new Error(`Missing complete Facilitator translation ${locale}.${key}`)
      }
      catalog.additional[source] = target[key] ?? source
    }

    for (let count = 0; count <= 4; count += 1) {
      const source = `${count} of 4 found on the public profile.`
      const translated =
        locale === "en"
          ? source
          : target.gearFound?.replace("{count}", String(count))
      if (!translated) {
        throw new Error(`Missing complete Facilitator translation ${locale}.gearFound`)
      }
      catalog.additional[source] = translated
    }
  }
}
