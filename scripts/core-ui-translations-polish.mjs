function setTranslation(catalogs, locale, source, translated) {
  const englishMessages = catalogs.en?.messages
  const targetCatalog = catalogs[locale]
  if (!englishMessages || !targetCatalog) return

  const messageKey = Object.entries(englishMessages).find(([, value]) => value === source)?.[0]
  if (messageKey) {
    targetCatalog.messages[messageKey] = translated
    return
  }

  targetCatalog.additional ??= {}
  targetCatalog.additional[source] = translated
}

export function applyCoreUiTranslationPolish(catalogs) {
  for (const [locale, translations] of Object.entries(CORE_UI_TRANSLATIONS)) {
    for (const [source, translated] of Object.entries(translations)) {
      setTranslation(catalogs, locale, source, translated)
    }
  }
}
