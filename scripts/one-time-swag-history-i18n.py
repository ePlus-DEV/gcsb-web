root = Path("public/i18n/locales")
for locale in ["en", *VALUES.keys()]:
    path = root / f"{locale}.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    additional = data.setdefault("additional", {})
    values = SOURCES if locale == "en" else VALUES[locale]
    if len(values) != len(SOURCES):
        raise SystemExit(f"{locale}: expected {len(SOURCES)} values, got {len(values)}")
    additional.update(dict(zip(SOURCES, values)))
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

print(f"Updated {1 + len(VALUES)} locale catalogs with {len(SOURCES)} historical Swag strings.")
