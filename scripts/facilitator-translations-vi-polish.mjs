export function applyVietnameseFacilitatorPolish(catalogs) {
  const catalog = catalogs.vi
  if (!catalog) throw new Error("The Vietnamese website locale catalog is missing.")

  catalog.additional ??= {}
  Object.assign(catalog.additional, VI_OVERRIDES, VI_DYNAMIC_OVERRIDES)

  for (let count = 0; count <= 4; count += 1) {
    catalog.additional[`${count} of 4 found on the public profile.`] =
      `${count} trên 4 huy hiệu được tìm thấy trong hồ sơ công khai.`
  }
}
